# ==================== 辅助函数 ====================

def get_prompts_by_scene(scene_id: int) -> tuple:
    """根据场景ID获取对应的提示词"""
    if scene_id == 0:  # 抛洒物
        return TASK1_SYSTEM_PROMPT, TASK1_USER_PROMPT
    elif scene_id == 1:  # 违停
        return TASK2_SYSTEM_PROMPT, TASK2_USER_PROMPT
    elif scene_id in [2, 3, 4, 5]:  # 路面护栏病害
        return TASK3_SYSTEM_PROMPT, TASK3_USER_PROMPT
    elif scene_id in [6, 7, 8]:  # 路外病害
        return TASK4_SYSTEM_PROMPT, TASK4_USER_PROMPT
    else:
        raise ValueError(f"未知的场景ID: {scene_id}")


def get_prompts_by_task(task_id: int) -> tuple:
    """根据任务ID获取对应的提示词"""
    if task_id == 1:
        return TASK1_SYSTEM_PROMPT, TASK1_USER_PROMPT
    elif task_id == 2:
        return TASK2_SYSTEM_PROMPT, TASK2_USER_PROMPT
    elif task_id == 3:
        return TASK3_SYSTEM_PROMPT, TASK3_USER_PROMPT
    elif task_id == 4:
        return TASK4_SYSTEM_PROMPT, TASK4_USER_PROMPT
    else:
        raise ValueError(f"未知的任务ID: {task_id}")
